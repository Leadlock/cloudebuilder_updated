/**
 * Pillar-centric view of an AssessmentReport, for the dedicated Well-Architected report.
 *
 * Nothing is recomputed here: scores, statuses, coverage, strengths and findings all come from the engine's
 * `pillarResults` as already placed in `report.wellArchitected`. This only re-orders and labels them.
 */
import type { Finding, Severity } from '@/lib/engines/assessment/types';
import { SEVERITY_ORDER } from '@/lib/engines/assessment/types';
import type { AssessmentReport } from './buildReport';

export interface WaPillarView {
  /** `provider:pillar`, the same key the AI review and its report commentary use. */
  key: string;
  provider: string;
  framework: string;
  pillar: string;
  label: string;
  referenceUrl: string;
  score: number | null;
  rating: string;
  status: string;
  coveragePct: number | null;
  evaluated: number;
  applicable: number;
  failed: number;
  warnings: number;
  passed: number;
  strengths: string[];
  /** Most severe first. */
  findings: Finding[];
  /** False when CloudCraft has too little evidence to say anything about this pillar. */
  evaluable: boolean;
}

const rank = (s: Severity) => SEVERITY_ORDER.indexOf(s);

export function waPillarViews(report: AssessmentReport): WaPillarView[] {
  return report.wellArchitected.flatMap((group) => group.pillars.map((p): WaPillarView => ({
    key: `${p.provider}:${p.pillar}`,
    provider: p.provider,
    framework: group.framework,
    pillar: p.pillar,
    label: p.label,
    referenceUrl: p.referenceUrl,
    score: p.score.score,
    rating: p.score.rating,
    status: p.status,
    coveragePct: p.score.coverage.coveragePct,
    evaluated: p.score.coverage.evaluated,
    applicable: p.score.coverage.applicable,
    failed: p.score.coverage.failed,
    warnings: p.score.coverage.warnings,
    passed: p.score.coverage.passed,
    strengths: p.strengths.slice(0, 4),
    findings: [...p.findings].sort((a, b) => rank(a.severity) - rank(b.severity)),
    evaluable: p.status !== 'Insufficient evidence' && p.score.score !== null,
  })));
}

/** Pillars with a score, strongest and weakest — for the one-line headline in the executive summary. */
export function strongestAndWeakest(views: WaPillarView[]): { strongest?: WaPillarView; weakest?: WaPillarView } {
  const scored = views.filter((v) => v.evaluable && v.score !== null);
  if (scored.length < 2) return {};
  const sorted = [...scored].sort((a, b) => (b.score as number) - (a.score as number));
  return { strongest: sorted[0], weakest: sorted[sorted.length - 1] };
}

