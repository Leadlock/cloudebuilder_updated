/**
 * A pillar score as text. A pillar resting on fewer than a handful of different checks is shown as indicative, never as a verdict:
 * two low-severity findings among two checks would otherwise read as a "25". `short` is for table cells.
 */
export function pillarScoreText(score: number | null, limitedEvidence: boolean, evaluatedRules: number, short = false): string {
  if (score === null) return 'Not scored';
  if (!limitedEvidence) return `${score}/100`;
  return short ? `${score}/100 (limited)` : `${score}/100 (indicative: limited evidence, ${evaluatedRules} check${evaluatedRules === 1 ? '' : 's'})`;
}

