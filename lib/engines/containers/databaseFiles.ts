/** The files that are specific to a database: its docker-compose.yml and README. (The deployment files come from the VM generators.) */
import type { ContainerConfig } from './dockerTemplates';
import { databaseOf } from './databases';

const yq = (s: string) => `"${s.replace(/[\\"]/g, (m) => `\\${m}`)}"`;

export function composeDatabase(c: ContainerConfig): string {
  const e = databaseOf(c)!;
  const env = [
    // Compose treats $ as interpolation, so a literal $ in a value is doubled.
    ...c.env.filter((v) => !v.secret).map((v) => `${v.key}: ${yq(v.value.replace(/\$/g, '$$$$'))}`),
    ...c.env.filter((v) => v.secret).map((v) => `${v.key}: "\${${v.key}:?set ${v.key}}"`),
  ];
  return `# Run with: docker compose up -d
# The database is published on this machine only (127.0.0.1), never on the network.
services:
  ${c.appName}:
    image: ${c.image}
    restart: ${c.restart}
    ports:
      - "127.0.0.1:${c.port}:${c.port}"
    environment:
${env.map((l) => `      ${l}`).join('\n')}
    volumes:
      - ${c.appName}-data:${e.dataPath}
${e.command ? `    command: ["sh", "-c", ${JSON.stringify(e.command)}]\n` : ''}    healthcheck:
      test: ["CMD-SHELL", ${yq(e.health)}]
      interval: 10s
      timeout: 5s
      retries: 12
      start_period: 20s
    mem_limit: ${c.memoryLimit}
    cpus: ${c.cpuLimit}
    security_opt:
      - no-new-privileges:true

volumes:
  ${c.appName}-data:
`;
}

export function readmeDatabase(c: ContainerConfig): string {
  const e = databaseOf(c)!;
  const secretNames = c.env.filter((v) => v.secret).map((v) => v.key);
  const vm = c.ec2.enabled ? 'EC2' : c.azvm.enabled ? 'Azure VM' : '';
  const cidr = c.ec2.enabled ? c.ec2.allowedCidr : c.azvm.allowedCidr;
  return `# ${c.appName}

Generated by CloudCraft Container Templates: ${e.label} ${c.version}, run from the official image \`${c.image}\`.

## Run locally

\`\`\`bash
cp .env.example .env   # set ${secretNames.join(', ')} (long, random, no spaces)
docker compose up -d
docker compose ps      # wait until it says "healthy"
\`\`\`

It listens on \`127.0.0.1:${c.port}\` (this machine only). An application connects with:

\`\`\`
${e.connection('localhost')}
\`\`\`

Use passwords without special characters (or URL-encode them): they are placed inside connection URLs.

## Your data

The data is kept in the Docker volume \`${c.appName}-data\` (${e.dataPath} in the container). It survives \`docker compose down\` and restarts; \`docker compose down -v\` deletes it.

## Back up

\`\`\`bash
${e.backup(c.appName)}
\`\`\`

Copy the file somewhere safe. Test a restore before you rely on it.
${vm ? `
## Deploy to ${vm}

\`bash deploy.sh\` creates one ${vm === 'EC2' ? 'instance' : 'virtual machine'} and starts ${e.label} on it. The passwords are read from ${vm === 'EC2' ? 'SSM Parameter Store' : 'Azure Key Vault'} (deploy.sh asks for them) and are never written to Terraform or its state.

- Port ${c.port} is open only to \`${cidr}\`. It is never open to the internet, so connect from inside that range (a VPN, a bastion, or your office address).
- The data is in the Docker volume \`${c.appName}-data\` on the machine's disk. It survives the container being replaced, but if the machine is deleted the data goes with it: take backups.
- Changing a setting and deploying again does **not** replace the machine or restart the database, so the data is safe. To apply a change, restart the container by hand on the machine, or replace the machine on purpose after a backup.
- This is one machine without failover. For production, consider ${vm === 'EC2' ? 'Amazon RDS / ElastiCache' : 'Azure Database'}.
` : ''}`;
}
