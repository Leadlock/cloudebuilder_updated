/**
 * Architecture Relationship Domain Model
 *
 * Provides normalized, semantically typed relationships between cloud resources.
 * Distinguishes network flows, data storage, load balancing, DNS resolution,
 * security associations, and cross-cloud bridges.
 */

export type RelationshipType =
  | 'NETWORK_FLOW'        // General directional network/IP traffic
  | 'ROUTES_TO'           // Gateway/Routing hops (IGW, NAT, Route Table, CloudFront Origin)
  | 'DEPENDS_ON'          // Upstream infrastructure or service dependency
  | 'CONNECTS_TO'         // TCP/UDP client-to-service connection (e.g. EC2 -> RDS)
  | 'LOAD_BALANCES'       // Traffic distribution across targets (ALB/NLB/App Gateway -> EC2/VMSS)
  | 'SERVES'              // Content delivery (e.g. CloudFront/FrontDoor serving cached assets)
  | 'READS_FROM'          // Read-only data access
  | 'WRITES_TO'           // Write data operations
  | 'STORES_IN'           // Object/Blob persistence (e.g. EC2/Lambda -> S3/Blob)
  | 'TRIGGERS'            // Event-driven execution (e.g. S3 -> Lambda, SQS -> Function)
  | 'AUTHENTICATES_WITH'  // IAM/Entra ID role or token validation
  | 'RESOLVES_TO'         // DNS hostname resolution (e.g. Route 53 -> CloudFront/ALB)
  | 'CONTAINS'            // Structural containment (rendered as container, not a network wire)
  | 'ASSOCIATED_WITH'     // Firewall/Security Group/WAF attachment
  | 'PEERS_WITH'          // VPC/VNet peering connection
  | 'REPLICATES_TO'       // Cross-region or cross-cloud replication
  | 'LOGICAL_DEPENDENCY'; // Higher-level architectural dependency

export type NetworkScope =
  | 'public'        // Traverses public Internet
  | 'private'       // Encapsulated within VPC/VNet private subnets
  | 'cross-vpc'     // Inter-VPC or peering
  | 'cross-region'  // Between regions within same cloud provider
  | 'cross-cloud'   // Spanning AWS and Azure
  | 'internal';     // Local loopback or intra-host

export type ValidationStatus = 'valid' | 'warning' | 'invalid';

export interface ArchitectureRelationship {
  id: string;
  sourceResourceId: string;
  targetResourceId: string;
  relationshipType: RelationshipType;
  direction: 'unidirectional' | 'bidirectional';
  protocol?: string;       // e.g. 'TCP', 'HTTPS', 'HTTP', 'PostgreSQL', 'MySQL', 'Redis', 'DNS', 'IAM'
  port?: string | number;  // e.g. 443, 80, 5432, 3306, 6379, 53
  networkScope: NetworkScope;
  provider: 'aws' | 'azure' | 'multi';
  region?: string;
  reason: string;          // Technical explanation or architectural evidence
  inferred: boolean;       // True if generated by engine, false if explicitly configured
  validationStatus: ValidationStatus;
  validationMessage?: string;
}

export interface ConnectionValidationResult {
  isValid: boolean;
  relationshipType: RelationshipType;
  protocol?: string;
  port?: string | number;
  label?: string;
  networkScope: NetworkScope;
  error?: {
    code: string;
    message: string;
    technicalReason: string;
    suggestedAlternatives: string[];
  };
}

/**
 * Workload specification for capacity sizing & reference architecture generation
 */
export interface WorkloadProfile {
  targetConcurrentUsers: number; // e.g. 1000
  targetRequestsPerSec: number;  // e.g. 150
  readWriteRatio: { read: number; write: number }; // e.g. { read: 80, write: 20 }
  availabilityTarget: number;    // e.g. 99.99
  environment: 'development' | 'staging' | 'production';
  workloadType: 'web' | 'api' | 'saas' | 'ecommerce' | 'data-processing';
  expectedDataSizeGb: number;
  storageRequirements: string;
  region: string;
}

/**
 * Capacity analysis estimate
 */
export interface CapacityEstimate {
  targetConcurrentUsers: number;
  calculatedCapacityUsers: number;
  capacityBufferRatio: number; // e.g. 1.5x (1,500 user capacity for 1,000 target)
  estimatedRps: number;
  appTierCapacityRps: number;
  dbTierCapacityRps: number;
  cacheHitRatio: number;
  cdnOffloadRatio: number;
  isAdequate: boolean;
  bottlenecks: string[];
  assumptions: string[];
  scalingStrategy: string;
  redundancyStrategy: string;
}
