/**
 * The generated Terraform of a project, packaged for the AWS Well-Architected Agent (preview), which reviews a zipped infrastructure-as-code project
 * (Terraform, CloudFormation or CDK) against a Well-Architected lens before anything is deployed. Nothing is sent to AWS: the person downloads the zip
 * and uploads it to the agent themselves, so what leaves CloudBuilder is their decision.
 *
 * The zip holds the Terraform files and a README, in a fixed order with a fixed time, so the same project always gives the same file. No state, no
 * credentials and no provider cache are ever included; the generator keeps secrets out of the files (variables without defaults).
 */
import { buildSourceZip, type ZipEntry } from '@/lib/deploy/project/zipWriter';

export interface AgentPackageInput {
  projectName: string;
  files: Array<{ filename: string; content: string }>;
  /** What the generator said about these files (unsupported types, settings to check). */
  warnings: string[];
  /** Problems that make Terraform fail only when AWS is asked to create something. */
  blocking?: string[];
  generatedAt: string;
}

export class AgentPackageError extends Error { constructor(message: string) { super(message); this.name = 'AgentPackageError'; } }

const SAFE_FILE = /^[A-Za-z0-9._-]+\.(tf|tfvars\.example|md)$/;

export function agentPackageReadme(i: AgentPackageInput): string {
  const lines = [
    `# ${i.projectName}: Terraform for the AWS Well-Architected Agent`, '',
    `Generated by CloudBuilder on ${i.generatedAt.slice(0, 10)}. This is the Terraform CloudBuilder generates for the project, packaged to be reviewed **before** anything is deployed.`, '',
    '## How to use it', '',
    '1. Open the AWS Well-Architected Agent (in preview at the time of writing; AWS says it runs in us-east-1, us-east-2 and us-west-2, and can analyse resources in any commercial Region, and may need an AWS Support plan: check the current AWS documentation).',
    '2. Start a review of an infrastructure-as-code project, upload this zip, and choose the Well-Architected lens you want.',
    '3. Read the findings and the suggested changes. Make the changes in CloudBuilder (the design is the source of truth), then generate and download the Terraform again, so the next review sees them.', '',
    '## What is in it', '',
    ...i.files.map((f) => `- \`terraform/${f.filename}\``), '',
    '## What is not in it', '',
    '- No Terraform state, no credentials, no provider cache and no secret values. Secrets are variables without defaults.',
    '- Anything outside your cloud account that the design uses (a third-party service such as Datadog or MongoDB Atlas): it is drawn and reviewed in CloudBuilder, but no code is generated for it, so the agent cannot see it.',
    '- Anything that is not Terraform: the application code, Dockerfiles and pipelines.', '',
    'The agent reviews the code it is given. It is not a CloudBuilder review, and CloudBuilder\'s own review of the same design (the Well-Architected tab) may find different things.', '',
  ];
  if ((i.blocking ?? []).length > 0) lines.push('## Fix before applying', '', 'These would make Terraform fail when AWS is asked to create resources. They do not stop a review of the code:', '', ...(i.blocking ?? []).slice(0, 30).map((b) => `- ${b}`), '');
  if (i.warnings.length > 0) lines.push('## Notes from the generator', '', ...i.warnings.slice(0, 40).map((w) => `- ${w}`), '');
  return lines.join('\n');
}

export function buildAgentPackage(i: AgentPackageInput): Buffer {
  const files = i.files.filter((f) => f.content.trim() !== '').sort((a, b) => a.filename.localeCompare(b.filename));
  if (files.length === 0) throw new AgentPackageError('There is no Terraform to package: save an architecture with AWS resources first.');
  for (const f of files) if (!SAFE_FILE.test(f.filename)) throw new AgentPackageError(`The file name ${JSON.stringify(f.filename.slice(0, 40))} is not allowed in the package.`);
  const entries: ZipEntry[] = [
    { path: 'README.md', content: agentPackageReadme({ ...i, files }) },
    ...files.map((f) => ({ path: `terraform/${f.filename}`, content: f.content })),
  ];
  return buildSourceZip(entries);
}
