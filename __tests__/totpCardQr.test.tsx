/**
 * @jest-environment jsdom
 */
/** The authenticator setup card shows a QR code that carries the same setup link, drawn in the browser, and still works without it. */
import React from 'react';
import { TextEncoder } from 'util';
// jsdom has no TextEncoder (the QR library uses it); every browser does.
Object.assign(globalThis, { TextEncoder });
import { render, screen, fireEvent, waitFor } from '@testing-library/react';

const mockToDataUrl = jest.fn();
jest.mock('qrcode', () => ({ __esModule: true, default: { toDataURL: (...a: unknown[]) => mockToDataUrl(...a) } }));

import TotpCard from '@/components/accounts/TotpCard';

const URI = 'otpauth://totp/CloudCraft:me%40x.test?secret=TXV4IOLZD2NYADGYQ6I2HMDIBM2KYM7R&issuer=CloudCraft';
const SECRET = 'TXV4IOLZD2NYADGYQ6I2HMDIBM2KYM7R';

function fakeServer() {
  const requested: string[] = [];
  (global as unknown as { fetch: unknown }).fetch = jest.fn(async (url: string, init?: { method?: string; body?: string }) => {
    requested.push(url);
    if (!init?.method) return { ok: true, json: async () => ({ ok: true, data: { enabled: false, recoveryCodesLeft: 0 } }) };
    const body = JSON.parse(init.body ?? '{}') as { action: string };
    if (body.action === 'begin') return { ok: true, json: async () => ({ ok: true, data: { secret: SECRET, uri: URI } }) };
    if (body.action === 'enable') return { ok: true, json: async () => ({ ok: true, data: { recoveryCodes: ['aaaa-bbbb'] } }) };
    return { ok: false, json: async () => ({ error: { message: 'no' } }) };
  });
  return requested;
}
async function openSetup() {
  render(<TotpCard />);
  fireEvent.change(await screen.findByLabelText('Your password'), { target: { value: 'pw' } });
  fireEvent.click(screen.getByRole('button', { name: 'Set up' }));
}

beforeEach(() => mockToDataUrl.mockReset());

describe('authenticator setup', () => {
  it('shows a QR code for the setup link, next to the typed key', async () => {
    mockToDataUrl.mockResolvedValue('data:image/png;base64,AAAA');
    const requested = fakeServer();
    await openSetup();
    const img = await screen.findByAltText('QR code that adds CloudCraft to your authenticator app');
    expect(img.getAttribute('src')).toBe('data:image/png;base64,AAAA');
    expect(mockToDataUrl).toHaveBeenCalledWith(URI, expect.objectContaining({ margin: 2, width: 200 }));
    expect(screen.getByText(/Scan a QR code/)).toBeTruthy();
    expect(screen.getByText(/Cannot scan it\? Choose/)).toBeTruthy();
    expect(screen.getByTestId('totp-secret').textContent).toBe('TXV4 IOLZ D2NY ADGY Q6I2 HMDI BM2K YM7R');
    // drawn in the browser: nothing was sent anywhere to make the picture
    expect(requested.every((u) => u.startsWith('/api/account/totp'))).toBe(true);
  });
  it('draws the code only for the key being set up, and removes it once the app is turned on', async () => {
    mockToDataUrl.mockResolvedValue('data:image/png;base64,AAAA');
    fakeServer();
    await openSetup();
    await screen.findByTestId('totp-qr');
    fireEvent.change(screen.getByPlaceholderText('6-digit code from the app'), { target: { value: '123456' } });
    fireEvent.click(screen.getByRole('button', { name: 'Turn on' }));
    await waitFor(() => expect(screen.queryByTestId('totp-qr')).toBeNull());
    expect(screen.queryByTestId('totp-secret')).toBeNull();
  });
  it('without a picture (it could not be drawn) the typed key and the link still work', async () => {
    mockToDataUrl.mockRejectedValue(new Error('no canvas'));
    fakeServer();
    await openSetup();
    expect(await screen.findByTestId('totp-secret')).toBeTruthy();
    await waitFor(() => expect(mockToDataUrl).toHaveBeenCalled());
    expect(screen.queryByTestId('totp-qr')).toBeNull();
    expect(screen.getByText(/open the setup link/)).toBeTruthy();
    expect(screen.queryByText(/Cannot scan it/)).toBeNull();
  });
  it('the code is a real, scannable QR code for that link (generated by the real library)', async () => {
    const real = jest.requireActual('qrcode') as { create: (t: string, o?: object) => { modules: { size: number; data: Uint8Array | number[] } } };
    const qr = real.create(URI, { errorCorrectionLevel: 'M' });
    expect(qr.modules.size).toBeGreaterThanOrEqual(33);          // a version-4 or larger symbol: the link needs it
    expect(Array.from(qr.modules.data).some((v) => v === 1)).toBe(true);
  });
});
