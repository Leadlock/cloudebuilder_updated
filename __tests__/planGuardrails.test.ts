import fs from 'fs';
import { evaluatePlanGuardrails, PlanGuardrailError, type PlanChangeForGuardrails, type PlanJsonForGuardrails } from '@/lib/terraform/execution/planGuardrails';
import { ALLOWED_TERRAFORM_RESOURCE_TYPES } from '@/lib/terraform/execution/allowedResourceTypes';
import { acquireProjectLock, releaseProjectLock } from '@/lib/terraform/execution/projectLock';
import { terraformExecutionDisabled } from '@/lib/terraform/execution/killSwitch';

const change = (type: string, after: Record<string, unknown> = {}, actions: string[] = ['create']): PlanChangeForGuardrails =>
  ({ address: `${type}.x`, type, mode: 'managed', change: { actions, after } });
const plan = (...rc: PlanChangeForGuardrails[]): PlanJsonForGuardrails => ({ resource_changes: rc });
const failed = (p: PlanJsonForGuardrails, opts = {}) => evaluatePlanGuardrails(p, opts).checks.filter((c) => !c.passed).map((c) => c.id);

describe('plan guardrails', () => {
  it('passes an ordinary plan', () => {
    const r = evaluatePlanGuardrails(plan(change('aws_vpc'), change('aws_instance'), change('aws_s3_bucket')), { maxResources: 200, allowedRegions: [] });
    expect(r.passed).toBe(true);
    expect(r.checks).toHaveLength(5);
  });

  it('refuses a resource type CloudCraft never generates (what an injected block would produce)', () => {
    expect(failed(plan(change('aws_iam_user'), change('aws_vpc')))).toEqual(['unexpected-types']);
    expect(failed(plan(change('null_resource')))).toEqual(['unexpected-types']);
    expect(failed(plan(change('terraform_data')))).toEqual(['unexpected-types']);
  });

  it('ignores unchanged, read-only and data resources', () => {
    const p = plan(change('aws_iam_user', {}, ['no-op']), change('aws_iam_user', {}, ['read']), { address: 'data.x', type: 'aws_iam_user', mode: 'data', change: { actions: ['create'] } });
    expect(evaluatePlanGuardrails(p, { maxResources: 200, allowedRegions: [] }).passed).toBe(true);
  });

  it('refuses administrator-style IAM', () => {
    const admin = JSON.stringify({ Statement: [{ Effect: 'Allow', Action: '*', Resource: '*' }] });
    const scoped = JSON.stringify({ Statement: [{ Effect: 'Allow', Action: ['s3:GetObject'], Resource: ['arn:aws:s3:::b/*'] }] });
    expect(failed(plan(change('aws_iam_user_policy', { policy: admin })))).toContain('unexpected-types'); // not even generated by CloudCraft
    expect(failed(plan(change('aws_iam_role_policy', { policy: admin })))).toEqual(['iam-admin']); // generated (container service), but never with admin rights
    expect(failed(plan(change('aws_iam_role_policy_attachment', { policy_arn: 'arn:aws:iam::aws:policy/AdministratorAccess' })))).toEqual(['iam-admin']);
    expect(failed(plan(change('aws_iam_role_policy_attachment', { policy_arn: 'arn:aws:iam::aws:policy/AmazonS3ReadOnlyAccess' })))).toEqual([]);
    expect(evaluatePlanGuardrails(plan(change('aws_iam_role_policy', { policy: scoped })), { maxResources: 200, allowedRegions: [] }).checks.find((c) => c.id === 'iam-admin')!.passed).toBe(true);
    expect(evaluatePlanGuardrails(plan(change('aws_iam_role_policy', { policy: admin })), { maxResources: 200, allowedRegions: [] }).checks.find((c) => c.id === 'iam-admin')!.passed).toBe(false);
  });

  it('refuses world-open admin ports and all-port rules, but allows 80/443', () => {
    const sg = (ingress: unknown[]) => change('aws_security_group', { ingress });
    expect(failed(plan(sg([{ cidr_blocks: ['0.0.0.0/0'], protocol: 'tcp', from_port: 22, to_port: 22 }])))).toEqual(['public-exposure']);
    expect(failed(plan(sg([{ cidr_blocks: ['0.0.0.0/0'], protocol: 'tcp', from_port: 3000, to_port: 4000 }, { cidr_blocks: ['0.0.0.0/0'], protocol: 'tcp', from_port: 0, to_port: 65535 }])))).toEqual(['public-exposure']);
    expect(failed(plan(sg([{ ipv6_cidr_blocks: ['::/0'], protocol: '-1', from_port: 0, to_port: 0 }])))).toEqual(['public-exposure']);
    expect(failed(plan(sg([{ cidr_blocks: ['0.0.0.0/0'], protocol: 'tcp', from_port: 443, to_port: 443 }, { cidr_blocks: ['0.0.0.0/0'], protocol: 'tcp', from_port: 80, to_port: 80 }])))).toEqual([]);
    expect(failed(plan(sg([{ cidr_blocks: ['10.0.0.0/8'], protocol: 'tcp', from_port: 22, to_port: 22 }])))).toEqual([]);
  });

  it('refuses public databases and public buckets', () => {
    expect(failed(plan(change('aws_db_instance', { publicly_accessible: true })))).toEqual(['public-exposure']);
    expect(failed(plan(change('aws_db_instance', { publicly_accessible: false })))).toEqual([]);
    expect(failed(plan(change('aws_s3_bucket_public_access_block', { block_public_acls: true, block_public_policy: false })))).toEqual(['public-exposure']);
    // the generator does not emit aws_s3_bucket_acl, so this is also an unexpected type — both checks fire
    expect(failed(plan(change('aws_s3_bucket_acl', { acl: 'public-read' })))).toEqual(expect.arrayContaining(['public-exposure']));
  });

  it('refuses a provider region outside the operator\'s allowed list — only when a list is set', () => {
    const p: PlanJsonForGuardrails = { resource_changes: [change('aws_vpc')], configuration: { provider_config: { aws: { expressions: { region: { constant_value: 'ap-south-1' } } } } } };
    expect(failed(p, { allowedRegions: ['us-east-1', 'eu-west-1'] })).toEqual(['region']);
    expect(failed(p, { allowedRegions: ['ap-south-1'] })).toEqual([]);
    expect(failed(p, { allowedRegions: [] })).toEqual([]);
    const unknown: PlanJsonForGuardrails = { resource_changes: [change('aws_vpc')], configuration: { provider_config: { aws: { expressions: {} } } } };
    expect(failed(unknown, { allowedRegions: ['us-east-1'] })).toEqual(['region']); // cannot be verified → refused
  });

  it('refuses a run that would touch more resources than the limit', () => {
    const many = plan(...Array.from({ length: 6 }, () => change('aws_vpc')));
    expect(failed(many, { maxResources: 5 })).toEqual(['size']);
    expect(failed(many, { maxResources: 6 })).toEqual([]);
  });

  it('PlanGuardrailError says which checks failed and why', () => {
    const report = evaluatePlanGuardrails(plan(change('aws_iam_user')), { maxResources: 200, allowedRegions: [] });
    const err = new PlanGuardrailError(report);
    expect(err.message).toMatch(/Plan blocked by safety checks/);
    expect(err.message).toContain('aws_iam_user');
    expect(err.report.passed).toBe(false);
  });
});

describe('allowed resource types stay in step with the generator', () => {
  it('lists exactly the Terraform resource types the generators can emit', () => {
    // The generator proper plus the Azure managed-service generators it calls.
    const src = ['lib/engines/terraform/TerraformGenerator.ts', 'lib/engines/terraform/azureServices.ts', 'lib/engines/terraform/containerService.ts'].map((f) => fs.readFileSync(f, 'utf8')).join('\n');
    const emitted = new Set([...src.matchAll(/resource "((?:aws|azurerm)_[a-z0-9_]+)"/g)].map((m) => m[1]!));
    for (const d of [...src.matchAll(/const resourceType\s*=\s*([^;]+);/g)].map((m) => m[1]!)) {
      for (const m of d.matchAll(/'((?:aws|azurerm)_[a-z0-9_]+)'/g)) emitted.add(m[1]!);
    }
    expect([...emitted].sort()).toEqual([...ALLOWED_TERRAFORM_RESOURCE_TYPES].sort());
  });
});

describe('per-project apply lock', () => {
  it('lets one apply run at a time and frees the project when it finishes', () => {
    const id = `lock-test-${Date.now()}`;
    expect(acquireProjectLock(id)).toBe(true);
    expect(acquireProjectLock(id)).toBe(false);
    expect(acquireProjectLock(`${id}-other`)).toBe(true);
    releaseProjectLock(id);
    expect(acquireProjectLock(id)).toBe(true);
    releaseProjectLock(id); releaseProjectLock(`${id}-other`);
  });
});

describe('kill switch', () => {
  const env = process.env as Record<string, string | undefined>;
  const saved = env.CLOUDCRAFT_TERRAFORM_DISABLED;
  afterEach(() => { if (saved === undefined) delete env.CLOUDCRAFT_TERRAFORM_DISABLED; else env.CLOUDCRAFT_TERRAFORM_DISABLED = saved; });
  it('is on only when explicitly set to 1', () => {
    delete env.CLOUDCRAFT_TERRAFORM_DISABLED;
    expect(terraformExecutionDisabled()).toBe(false);
    env.CLOUDCRAFT_TERRAFORM_DISABLED = '1';
    expect(terraformExecutionDisabled()).toBe(true);
    env.CLOUDCRAFT_TERRAFORM_DISABLED = '0';
    expect(terraformExecutionDisabled()).toBe(false);
  });
});
